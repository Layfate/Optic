import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { root, readModules, loader } from './modules.mjs';

const modules = await readModules();
const entry = await readFile(path.join(root, 'src/init.server.luau'), 'utf8');
if (!modules.App) throw new Error('The App module is missing.');
const escape = s => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;');
const properties = (name, source) => `<Properties><string name="Name">${escape(name)}</string><ProtectedString name="Source">${escape(source)}</ProtectedString></Properties>`;
const xml = '<?xml version="1.0" encoding="utf-8"?>\n<roblox version="4">'
  + '<Item class="Script" referent="OpticRoot">' + properties('Optic', entry)
  + Object.entries(modules).map(([name, source]) => `<Item class="ModuleScript" referent="Optic${name}">${properties(name, source)}</Item>`).join('')
  + '</Item></roblox>\n';
const bundle = '-- Optic 0.1.0 — generated by npm run build; edit src/ instead.\n'
  + loader(modules) + '\nassert(plugin, "Optic must run as a Roblox Studio plugin.")\n__require(__root.App).start(plugin)\n';
await mkdir(path.join(root, 'dist'), { recursive: true });
await writeFile(path.join(root, 'dist/Optic.rbxmx'), xml);
await writeFile(path.join(root, 'dist/Optic.plugin.luau'), bundle);
console.log(`Built Optic.rbxmx (${Buffer.byteLength(xml)} bytes) and Optic.plugin.luau (${Buffer.byteLength(bundle)} bytes).`);
